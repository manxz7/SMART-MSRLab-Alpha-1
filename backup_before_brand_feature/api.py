# ─────────────────────────────────────────────
# ENDPOINT 2: Search Products
# URL: GET http://localhost:8000/search?q=milo
# URL: GET http://localhost:8000/search?q=nestle&category=Produk
#
# Purpose: Search halal products by company name OR brand name.
# Supports optional filtering by category.
# Returns up to 50 results.
# ─────────────────────────────────────────────
@app.get("/search")
def search_products(
    q: str = Query(..., min_length=2, description="Search keyword (company name or brand)"),
    category: str = Query(None, description="Filter by category (optional). E.g: Produk, Syarikat, Kosmetik"),
    limit: int = Query(50, ge=1, le=200, description="Max number of results to return (default 50, max 200)"),
):
    """
    Search halal-certified products and companies.

    - **q**: The search keyword. Searches both company name and brand name.
    - **category**: Optional. Filter to a specific JAKIM category.
    - **limit**: How many results to return (max 200).
    """
    try:
        conn = get_db_connection()
        # RealDictCursor makes each row come back as a Python dict (like a JSON object)
        # instead of a plain tuple like (1, "Nestle", "Milo", ...)
        cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)

        # Build the SQL query dynamically
        # ILIKE = case-insensitive search. '%milo%' matches 'MILO', 'Milo 3in1', etc.
        if category:
            # Search with category filter
            cur.execute(
                """
                SELECT id, category, comp_code, company, brand, address, expiry
                FROM halal_products
                WHERE (company ILIKE %s OR brand ILIKE %s)
                  AND category = %s
                ORDER BY company
                LIMIT %s
                """,
                (f"%{q}%", f"%{q}%", category, limit)
            )
        else:
            # Search across ALL categories
            cur.execute(
                """
                SELECT id, category, comp_code, company, brand, address, expiry
                FROM halal_products
                WHERE company ILIKE %s OR brand ILIKE %s
                ORDER BY company
                LIMIT %s
                """,
                (f"%{q}%", f"%{q}%", limit)
            )

        rows = cur.fetchall()
        cur.close()
        conn.close()

        return {
            "query": q,
            "category_filter": category,
            "count": len(rows),
            "results": rows
        }

    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Search failed: {str(e)}")


