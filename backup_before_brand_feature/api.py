# ─────────────────────────────────────────────
# AI IMAGE SIMILARITY — loaded once at startup
# embeddings.npz is generated by build_embeddings.py
# ─────────────────────────────────────────────
EMBEDDINGS_FILE = "embeddings.npz"
_embed_model    = None   # EfficientNet-B0 feature extractor
_embeddings     = None   # shape (N, 1280) — all product fingerprints
_names          = None   # product name for each row
_categories     = None   # Lotus category for each row
_filenames      = None   # image filename for each row

# ─────────────────────────────────────────────
# OCR — PaddleOCR for text extraction from images
# ─────────────────────────────────────────────
_ocr = None   # PaddleOCR instance


def _load_ai_models():
    """Load EfficientNet + embeddings index into memory (called once at startup)."""
    global _embed_model, _embeddings, _names, _categories, _filenames

    if not os.path.exists(EMBEDDINGS_FILE):
        print(f"[AI] WARNING: {EMBEDDINGS_FILE} not found — /scan-image will be unavailable")
        print("[AI] Run  python build_embeddings.py  to generate it first.")
        return

    print("[AI] Loading EfficientNet-B0...")
    import tensorflow as tf
    from tensorflow.keras.applications import EfficientNetB0
    _embed_model = EfficientNetB0(
        weights="imagenet",
        include_top=False,
        pooling="avg",
        input_shape=(224, 224, 3),
    )
    _embed_model.trainable = False

    print(f"[AI] Loading embeddings from {EMBEDDINGS_FILE}...")
    data = np.load(EMBEDDINGS_FILE, allow_pickle=True)
    _embeddings = data["embeddings"].astype(np.float32)   # (N, 1280)
    _names      = data["names"]
    _categories = data["categories"]
    _filenames  = data["filenames"]
    print(f"[AI] Ready — {len(_names)} product fingerprints loaded")


def _load_ocr_model():
    """Load EasyOCR model into memory (called once at startup)."""
    global _ocr
    try:
        import easyocr
        print("[OCR] Loading EasyOCR (en + ms)...")
        _ocr = easyocr.Reader(['en', 'ms'], gpu=False, verbose=False)
        print("[OCR] EasyOCR ready")
    except Exception as e:
        print(f"[OCR] WARNING: EasyOCR not available — {e}")
        _ocr = None


def _extract_text_ocr(image_bytes: bytes) -> list:
    """Extract text strings from image using EasyOCR."""
    if _ocr is None:
        print("[OCR] _ocr is None — model not loaded!")
        return []
    try:
        result = _ocr.readtext(image_bytes, detail=1)
        print(f"[OCR] Raw results ({len(result)} items):")
        texts = []
        for (_, text, confidence) in result:
            print(f"  [{confidence:.2f}] {text!r}")
            if confidence > 0.3 and len(text.strip()) > 1:
                texts.append(text.strip())
        return texts
    except Exception as e:
        print(f"[OCR] Extraction error: {e}")
        return []


def _search_jakim_by_texts(texts: list) -> list:
    """Search JAKIM DB using OCR-extracted text strings. Returns merged unique results."""
    if not texts:
        return []

    # Build search terms: original texts + individual tokens from multi-word strings
    # e.g. ["FERRERO ROCHER 24", "300g"] → search "FERRERO ROCHER 24", "FERRERO", "ROCHER", "300g"
    import re
    search_terms = []
    seen_terms = set()
    for text in texts[:8]:
        text = text.strip()
        if len(text) < 3:
            continue
        if text.lower() not in seen_terms:
            seen_terms.add(text.lower())
            search_terms.append(text)
        # Also add individual meaningful words from multi-word OCR hits
        if " " in text:
            for word in text.split():
                word = word.strip()
                # Skip pure numbers, short words, and common noise
                if len(word) >= 3 and not re.fullmatch(r'[\d\.\,\-\(\)]+', word):
                    if word.lower() not in seen_terms:
                        seen_terms.add(word.lower())
                        search_terms.append(word)

    if not search_terms:
        return []

    try:
        conn = get_db_connection()
        cur  = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
        results = []
        seen_ids = set()
        for term in search_terms[:12]:
            cur.execute(
                """
                SELECT id, category, comp_code, company, brand, address, expiry
                FROM halal_products
                WHERE company ILIKE %s OR brand ILIKE %s
                ORDER BY company
                LIMIT 5
                """,
                (f"%{term}%", f"%{term}%")
            )
            for row in cur.fetchall():
                if row["id"] not in seen_ids:
                    seen_ids.add(row["id"])
                    results.append(dict(row))
        cur.close()
        conn.close()

        # Rank: records that match more search terms appear first
        def relevance(record):
            combined = f"{record.get('company','') or ''} {record.get('brand','') or ''}".lower()
            return sum(1 for t in search_terms if t.lower() in combined)

        results.sort(key=relevance, reverse=True)
        return results[:20]
    except Exception:
        return []


