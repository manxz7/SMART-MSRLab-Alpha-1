# ─────────────────────────────────────────────
# ENDPOINT 5: Image Similarity Search (AI)
# URL: POST http://localhost:8000/scan-image
# Body: multipart/form-data with field "file" = image
#
# Purpose: User uploads a photo of a product.
# We extract an EfficientNet-B0 fingerprint, compare it
# against all stored product fingerprints, and return the
# closest match along with its JAKIM halal status.
# ─────────────────────────────────────────────
@app.post("/scan-image")
async def scan_image(file: UploadFile = File(...)):
    """
    Identify a product from a photo and check its JAKIM halal status.

    Pipeline:
      1. PaddleOCR  — extract text from label (product name, brand, cert no.)
      2. EfficientNet — image similarity fallback if OCR finds nothing useful
    Both results are merged and checked against the JAKIM halal database.
    """
    # ── Validate file type ──────────────────────────────────────────────────
    ct = (file.content_type or "").lower()
    if ct and not ct.startswith("image/") and ct != "application/octet-stream":
        raise HTTPException(status_code=400, detail="Only image files are accepted.")

    # ── Read image bytes ────────────────────────────────────────────────────
    try:
        image_bytes = await file.read()
        if len(image_bytes) > 10 * 1024 * 1024:
            raise HTTPException(status_code=400, detail="Image too large. Maximum 10 MB.")
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Could not read image: {str(e)}")

    # ── METHOD 1: OCR — extract text from product label, search JAKIM ────────
    ocr_texts  = _extract_text_ocr(image_bytes)
    ocr_halal  = _search_jakim_by_texts(ocr_texts)
    print(f"[OCR] Extracted {len(ocr_texts)} texts: {ocr_texts}")
    print(f"[OCR] JAKIM matches: {len(ocr_halal)}")

    # ── METHOD 2: EfficientNet — fallback ONLY if OCR found no JAKIM results ──
    matched_name     = None
    matched_category = None
    matched_filename = None
    confidence       = None
    efficientnet_halal = []

    if len(ocr_halal) == 0 and _embed_model is not None and _embeddings is not None:
        try:
            from tensorflow.keras.applications.efficientnet import preprocess_input

            img = Image.open(io.BytesIO(image_bytes)).convert("RGB")
            img = img.resize((224, 224), Image.LANCZOS)
            arr = np.array(img, dtype=np.float32)
            arr = preprocess_input(arr)
            arr = np.expand_dims(arr, axis=0)

            query_vec = _embed_model.predict(arr, verbose=0)[0]
            norm = np.linalg.norm(query_vec)
            if norm > 0:
                query_vec = query_vec / norm

            similarities = _embeddings @ query_vec
            top_idx      = int(np.argmax(similarities))
            confidence   = round(float(similarities[top_idx]), 4)

            matched_name     = str(_names[top_idx])
            matched_category = str(_categories[top_idx])
            matched_filename = str(_filenames[top_idx])

            # Search JAKIM with matched product name (first 3 words)
            search_term = " ".join(matched_name.split()[:3])
            try:
                conn = get_db_connection()
                cur  = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
                cur.execute(
                    """
                    SELECT id, category, comp_code, company, brand, address, expiry
                    FROM halal_products
                    WHERE company ILIKE %s OR brand ILIKE %s
                    ORDER BY company LIMIT 10
                    """,
                    (f"%{search_term}%", f"%{search_term}%")
                )
                efficientnet_halal = [dict(r) for r in cur.fetchall()]
                cur.close()
                conn.close()
            except Exception:
                pass
        except Exception as e:
            print(f"[EfficientNet] Error: {e}")

    # ── Merge halal results (OCR first, then EfficientNet, deduplicated) ─────
    seen_ids = set()
    merged_halal = []
    for record in ocr_halal + efficientnet_halal:
        if record["id"] not in seen_ids:
            seen_ids.add(record["id"])
            merged_halal.append(record)

    # ── Determine which methods contributed ─────────────────────────────────
    if ocr_halal:
        detection_method = "ocr"
    elif matched_name:
        detection_method = "efficientnet"
    else:
        detection_method = "none"

    return {
        "ocr_texts":        ocr_texts,
        "matched_product":  matched_name,
        "matched_category": matched_category,
        "matched_filename": matched_filename,
        "confidence":       confidence,
        "halal_records":    merged_halal,
        "halal_count":      len(merged_halal),
        "detection_method": detection_method,
        "note": (
            "OCR reads text from product label and searches JAKIM. "
            "EfficientNet image similarity is used only if OCR finds no results."
        ),
    }
